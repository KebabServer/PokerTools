#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
compiler="${CLANG:-clang-19}"
wasm="$(mktemp)"
trap 'rm -f "$wasm"' EXIT
"$compiler" --target=wasm32 -mbulk-memory -std=c11 -O3 -Wall -Wextra -Werror -ffp-contract=off \
  -nostdlib -fno-builtin -Wl,--no-entry,--import-memory,--export=__stack_pointer,--strip-all,-z,stack-size=0 \
  solver/native/solver.c -o "$wasm"
node --input-type=module - "$wasm" <<'JS'
import { readFileSync, writeFileSync } from 'node:fs'
const bytes = readFileSync(process.argv[2])
const path = 'public/turn-river-lab/native-kernel-data.js'
const source = '// Generated by scripts/build-turn-river-wasm.sh from solver/native/solver.c.\n' +
  'const WASM_LOCK_KERNEL_BYTES = ' + JSON.stringify(bytes.toString('base64')) + ';\n'
if (process.env.CHECK === '1') {
  if (source !== readFileSync(path, 'utf8')) throw Error('Generated WASM differs.')
} else {
  writeFileSync(path, source)
}
JS
