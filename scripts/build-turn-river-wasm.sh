#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
compiler="${CLANG:-clang-19}"
build="$(mktemp -d)"
trap 'rm -rf "$build"' EXIT
for variant in scalar simd; do
  flags=()
  if [[ "$variant" == simd ]]; then flags=(-msimd128); fi
  "$compiler" --target=wasm32 -mbulk-memory "${flags[@]}" -std=c11 -O3 -Wall -Wextra -Werror -ffp-contract=off \
    -nostdlib -fno-builtin -Wl,--no-entry,--import-memory,--export=__stack_pointer,--strip-all,-z,stack-size=0 \
    solver/native/solver.c -o "$build/$variant.wasm"
done
node --input-type=module - "$build" <<'JS'
import { readFileSync, writeFileSync } from 'node:fs'
const path = 'public/turn-river-lab/native-kernel-data.js'
const variants = { WASM_LOCK_KERNEL_BYTES: 'scalar', WASM_SOURCE_SIMD_BYTES: 'simd' }
const source = '// Generated by scripts/build-turn-river-wasm.sh from solver/native/solver.c.\n' +
  Object.entries(variants).map(([name, variant]) =>
    'const ' + name + ' = ' + JSON.stringify(readFileSync(process.argv[2] + '/' + variant + '.wasm').toString('base64')) + ';\n').join('')
if (process.env.CHECK === '1') {
  if (source !== readFileSync(path, 'utf8')) throw Error('Generated WASM differs.')
} else {
  writeFileSync(path, source)
}
JS
